"""Reconstruct the original tested manifold voxel budget in an owned local cache.

The shared test cache is being regenerated by another background task. This
isolated reproduction uses the supplied source, the original 4mm voxel setting,
and a 4500-triangle budget. Later armchair cleanup performs no collapse step.
"""
from pathlib import Path
import bpy,bmesh,numpy as np,sys,json,hashlib
from mathutils import Vector
OUT=Path(__file__).resolve().parent;INPUT=OUT/'input';TEX=INPUT/'budget_tex'
SOURCE=Path('C:/Users/alexw/AppData/Roaming/StabilityMatrix/Packages/ComfyUI/output/valetf_b_armchair_full_00001_.glb')
def select(ob):
    bpy.ops.object.select_all(action='DESELECT');ob.select_set(True);bpy.context.view_layer.objects.active=ob
def main():
    INPUT.mkdir(exist_ok=True);TEX.mkdir(exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=str(SOURCE),merge_vertices=True)
    meshes=[o for o in bpy.context.scene.objects if o.type=='MESH']
    for o in meshes:
        m=o.matrix_world.copy();o.parent=None;o.matrix_world=m
    for o in list(bpy.context.scene.objects):
        if o not in meshes:bpy.data.objects.remove(o,do_unlink=True)
    bpy.ops.object.select_all(action='DESELECT')
    for o in meshes:o.select_set(True)
    bpy.context.view_layer.objects.active=meshes[0]
    if len(meshes)>1:bpy.ops.object.join()
    high=bpy.context.active_object;select(high);bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
    p=np.array([v.co[:]for v in high.data.vertices]);lo=p.min(0);hi=p.max(0);center=(lo+hi)*.5
    for v in high.data.vertices:v.co-=Vector((center[0],center[1],lo[2]))
    high.data.update()
    low=high.copy();low.data=high.data.copy();bpy.context.scene.collection.objects.link(low);select(low)
    while low.data.uv_layers:low.data.uv_layers.remove(low.data.uv_layers[0])
    try:bpy.ops.mesh.customdata_custom_splitnormals_clear()
    except Exception:pass
    vox=low.modifiers.new('Original4mmVoxel','REMESH');vox.mode='VOXEL';vox.voxel_size=.004
    bpy.ops.object.modifier_apply(modifier=vox.name)
    low.data.calc_loop_triangles();d=low.modifiers.new('Original4500Budget','DECIMATE')
    d.ratio=4500/len(low.data.loop_triangles);d.use_collapse_triangulate=True
    bpy.ops.object.modifier_apply(modifier=d.name);bpy.ops.object.shade_smooth()
    select(low);low.data.uv_layers.new(name='UVMap')
    bpy.ops.object.mode_set(mode='EDIT');bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=1.151917,island_margin=.004,area_weight=0,correct_aspect=True,scale_to_bounds=False)
    bpy.ops.object.mode_set(mode='OBJECT')
    m=bpy.data.materials.new('M_Armchair_InputBake');m.use_nodes=True;low.data.materials.clear();low.data.materials.append(m)
    nt=m.node_tree;p=next(n for n in nt.nodes if n.type=='BSDF_PRINCIPLED');images={}
    sc=bpy.context.scene;sc.render.engine='CYCLES';sc.cycles.samples=4;sc.cycles.device='CPU'
    sc.render.bake.use_selected_to_active=True;sc.render.bake.cage_extrusion=.015;sc.render.bake.max_ray_distance=.04;sc.render.bake.margin=8
    for key,btype in [('basecolor','DIFFUSE'),('normal','NORMAL')]:
        im=bpy.data.images.new('b_armchair_budget_'+key,2048,2048,alpha=False)
        im.colorspace_settings.name='sRGB'if key=='basecolor'else'Non-Color'
        n=nt.nodes.new('ShaderNodeTexImage');n.image=im;nt.nodes.active=n
        select(low);high.select_set(True)
        if key=='basecolor':bpy.ops.object.bake(type=btype,pass_filter={'COLOR'})
        else:bpy.ops.object.bake(type=btype,normal_space='TANGENT')
        im.filepath_raw=str(TEX/f'b_armchair_budget_{key}.png');im.file_format='PNG';im.save();images[key]=n
    nt.links.new(images['basecolor'].outputs['Color'],p.inputs['Base Color'])
    nm=nt.nodes.new('ShaderNodeNormalMap');nt.links.new(images['normal'].outputs['Color'],nm.inputs['Color']);nt.links.new(nm.outputs['Normal'],p.inputs['Normal'])
    select(low);low.name='ACH_SourceBudget'
    bpy.ops.export_scene.gltf(filepath=str(INPUT/'armchair_clean_input.glb'),use_selection=True,export_format='GLB',export_yup=True)
    bm=bmesh.new();bm.from_mesh(low.data)
    report={'source':str(SOURCE),'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
            'triangles':sum(len(f.verts)-2 for f in bm.faces),'vertices':len(bm.verts),
            'boundary_edges':sum(e.is_boundary for e in bm.edges),'nonmanifold_edges':sum(not e.is_manifold for e in bm.edges),
            'method':'reproduction of initial tested 4mm voxel + 4500 budget; isolated from live shared-test rewrites'}
    bm.free();(INPUT/'input_qa.json').write_text(json.dumps(report,indent=2)+'\n');print('INPUT_READY',json.dumps(report),flush=True)
if __name__=='__main__':main()
