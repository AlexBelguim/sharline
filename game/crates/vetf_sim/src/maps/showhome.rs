/// Gives a brush with a side plane off the axes (the curved kerb units, the charger island's) its axial bevels:
/// the ±X and ±Z planes of its bounds. The box trace pushes every plane out by the box's extent along it, which
/// round a corner between two turned faces reaches past the real shape: without the bevels a player box 8 mm
/// clear of a kerb unit started solid, and the controller stopped dead in front of the 11 cm kerb (and cancelled
/// a jump while forward was held) instead of stepping up (map-kit review K1).
pub(crate) fn bevel_sides(b: &mut crate::movement::collision::Brush) {
    use crate::movement::collision::Plane;
    use glam::Vec3;
    let axial = |n: Vec3| n.x.abs() > 0.999 || n.y.abs() > 0.999 || n.z.abs() > 0.999;
    if b.planes.iter().all(|p| axial(p.normal)) {
        return;
    }
    let (min, max) = (b.min, b.max);
    for (normal, dist) in [(Vec3::X, max.x), (Vec3::NEG_X, -min.x), (Vec3::Z, max.z), (Vec3::NEG_Z, -min.z)] {
        if !b.planes.iter().any(|p| p.normal.abs_diff_eq(normal, 1e-4)) {
            b.planes.push(Plane { normal, dist });
        }
    }
}

